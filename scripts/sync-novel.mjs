// Sync locked chapter Markdown from ../publishing/book/chapters into src/data/chapters.ts.
// Usage: npm run sync-novel
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const bookDir = path.resolve(here, "..", "..", "publishing", "book");
const chaptersDir = path.join(bookDir, "chapters");
const outFile = path.resolve(here, "..", "src", "data", "chapters.ts");

const isRule = (l) => /^(\* \* \*|-{3,}|\*{3,}|\\\*)$/.test(l.trim());
const stripInline = (s) =>
  s
    .replace(/\\([*_`\[\]\\-])/g, "$1")
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/(^|[^*])\*(?!\s)(.+?)\*(?!\*)/g, "$1$2")
    .replace(/\s+/g, " ")
    .trim();

function parseChapter(md, file) {
  const lines = md.replace(/\r/g, "").split("\n");
  let title = "";
  let epigraph = "";
  const scenes = [[]];
  let buf = [];
  const flush = () => {
    if (buf.length) scenes[scenes.length - 1].push(stripInline(buf.join(" ")));
    buf = [];
  };
  for (const raw of lines) {
    const line = raw.trim();
    if (!title && line.startsWith("# ")) { title = line.slice(2).trim(); continue; }
    if (!line) { flush(); continue; }
    if (isRule(line)) {
      flush();
      if (scenes[scenes.length - 1].length) scenes.push([]);
      continue;
    }
    // First italic-only paragraph before any prose is the epigraph.
    if (!epigraph && scenes.length === 1 && scenes[0].length === 0 && /^\*[^*].*\*$/.test(line)) {
      epigraph = stripInline(line);
      continue;
    }
    buf.push(line);
  }
  flush();
  const m = path.basename(file).match(/^(\d+)-(.+)\.md$/);
  const number = m ? parseInt(m[1], 10) : 0;
  const slug = m ? m[2] : path.basename(file, ".md");
  const clean = scenes.filter((s) => s.length);
  const words = clean.flat().join(" ").split(/\s+/).filter(Boolean).length;
  return { number, slug, title, epigraph, scenes: clean, words };
}

async function main() {
  // Standalone clones (CI, Vercel, GitHub) don't have ../publishing: keep the committed data.
  const hasBook = await fs.stat(chaptersDir).then((s) => s.isDirectory(), () => false);
  if (!hasBook) {
    const hasData = await fs.stat(outFile).then(() => true, () => false);
    if (!hasData) throw new Error(`No chapters at ${chaptersDir} and no committed ${outFile}`);
    console.log("sync-novel: publishing/book not found; using committed src/data/chapters.ts");
    return;
  }
  const yaml = await fs.readFile(path.join(bookDir, "book.yaml"), "utf8").catch(() => "");
  const bookTitle = (yaml.match(/^title:\s*(.+)$/m)?.[1] ?? "The Pages Between Us").trim();
  const files = (await fs.readdir(chaptersDir)).filter((f) => /^\d+-.+\.md$/.test(f)).sort();
  const chapters = [];
  for (const f of files) {
    const md = await fs.readFile(path.join(chaptersDir, f), "utf8");
    chapters.push(parseChapter(md, f));
  }
  const out =
    `// AUTO-GENERATED by scripts/sync-novel.mjs from publishing/book/chapters. Do not edit by hand.\n` +
    `export interface Chapter {\n  number: number;\n  slug: string;\n  title: string;\n  epigraph: string;\n  scenes: string[][];\n  words: number;\n}\n\n` +
    `export const BOOK_TITLE = ${JSON.stringify(bookTitle)};\n\n` +
    `export const chapters: Chapter[] = ${JSON.stringify(chapters, null, 2)};\n`;
  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, out, "utf8");
  for (const c of chapters)
    console.log(`synced ch${String(c.number).padStart(2, "0")} "${c.title}": ${c.scenes.length} scenes, ${c.words} words`);
}

main().catch((e) => { console.error(e); process.exit(1); });
